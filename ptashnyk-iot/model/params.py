# --- Зовнішня температура: від -9 до -1 °C, максимум о 15:00 --------------
def t_outdoor(t_s: float) -> float:
    h = t_s / 3600.0
    return -5.0 + 4.0 * math.sin(2 * math.pi * (h - 9.0) / 24.0)

